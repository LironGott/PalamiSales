"""Clause texts for the PALAMI service agreements.

A value may be a plain string (same in both versions) or V(agency, independent).
Use None in one side of V() to drop an item from that version.
Fill-in blanks: [[]] normal, [[s]] short, [[l]] long.
Copy rules (CLAUDE.md): gender-neutral, no comma before a word starting with the conjunction "ו", "הכל" without vav,
"מסמכים" for what the agent uploads, dates DD.MM.YYYY.
"""


class _V(dict):
    """Per-version text that can be concatenated with plain strings or other _V values."""
    def _get(self, o, k):
        return o[k] if isinstance(o, dict) else o

    def __add__(self, o):
        return _V({k: self[k] + self._get(o, k) for k in self})

    def __radd__(self, o):
        return _V({k: self._get(o, k) + self[k] for k in self})


def V(agency, independent):
    return _V(agency=agency, independent=independent)


